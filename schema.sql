create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 2 and 24),
  game_name text default '',
  bio text default '',
  updated_at timestamptz default now()
);
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  channel text not null default 'global' check (channel in ('global','lobbies')),
  content text not null check (char_length(content) between 1 and 500),
  created_at timestamptz not null default now()
);
create table if not exists public.lobbies (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references public.profiles(id) on delete cascade,
  title text not null check (char_length(title) between 2 and 40),
  description text default '',
  max_players int not null default 4 check (max_players between 2 and 8),
  status text not null default 'open' check (status in ('open','closed')),
  created_at timestamptz not null default now()
);
create table if not exists public.lobby_requests (
  id bigint generated by default as identity primary key,
  lobby_id bigint not null references public.lobbies(id) on delete cascade,
  requester_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(lobby_id, requester_id)
);
create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null check (char_length(title) between 2 and 70),
  body text not null check (char_length(body) between 1 and 1000),
  created_at timestamptz not null default now()
);
create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid not null references public.profiles(id) on delete cascade,
  content_type text not null check (content_type in ('post')),
  content_id text not null,
  reason text not null check (char_length(reason) between 2 and 300),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.messages enable row level security;
alter table public.lobbies enable row level security;
alter table public.lobby_requests enable row level security;
alter table public.posts enable row level security;
alter table public.reports enable row level security;

create policy "Profiles are readable by signed-in users" on public.profiles for select to authenticated using (true);
create policy "Users create own profile" on public.profiles for insert to authenticated with check (auth.uid() = id);
create policy "Users update own profile" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

create policy "Signed-in users read chat" on public.messages for select to authenticated using (true);
create policy "Users send own chat messages" on public.messages for insert to authenticated with check (auth.uid() = user_id);

create policy "Signed-in users read lobbies" on public.lobbies for select to authenticated using (true);
create policy "Users create own lobbies" on public.lobbies for insert to authenticated with check (auth.uid() = owner_id);
create policy "Hosts update own lobbies" on public.lobbies for update to authenticated using (auth.uid() = owner_id) with check (auth.uid() = owner_id);

create policy "Users see requests they sent or received" on public.lobby_requests for select to authenticated using (
  auth.uid() = requester_id or exists(select 1 from public.lobbies l where l.id = lobby_id and l.owner_id = auth.uid())
);
create policy "Users request to join" on public.lobby_requests for insert to authenticated with check (auth.uid() = requester_id);

create policy "Signed-in users read posts" on public.posts for select to authenticated using (true);
create policy "Users create own posts" on public.posts for insert to authenticated with check (auth.uid() = user_id);
create policy "Users delete own posts" on public.posts for delete to authenticated using (auth.uid() = user_id);

create policy "Users submit reports" on public.reports for insert to authenticated with check (auth.uid() = reporter_id);

